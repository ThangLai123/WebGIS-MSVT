-- 1. Hàm tự động cập nhật thời gian updated_at khi sửa bản ghi
CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 2. Tạo bảng quản lý vùng trồng (public.vung_trong)
CREATE TABLE IF NOT EXISTS public.vung_trong (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msvt_moi TEXT,
    msvt_cu TEXT,
    to_chuc_ca_nhan TEXT,
    nguoi_dai_dien TEXT,
    so_dien_thoai TEXT,
    email TEXT,
    toa_do_goc TEXT,
    dia_chi_msvt TEXT,
    loai_cay_trong TEXT,
    so_ho_tham_gia INTEGER,
    dien_tich_ha NUMERIC(14,4),
    san_luong_tan_ha NUMERIC(14,4),
    quy_trinh TEXT,
    thi_truong TEXT,
    vi_tri GEOMETRY(Point, 4326),
    ranh_gioi GEOMETRY(MultiPolygon, 4326),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),

    -- Ràng buộc kiểm tra tính hợp lệ dữ liệu (CHECK constraint)
    CONSTRAINT check_so_ho_tham_gia CHECK (so_ho_tham_gia IS NULL OR so_ho_tham_gia >= 0),
    CONSTRAINT check_dien_tich_ha CHECK (dien_tich_ha IS NULL OR dien_tich_ha >= 0),
    CONSTRAINT check_san_luong_tan_ha CHECK (san_luong_tan_ha IS NULL OR san_luong_tan_ha >= 0)
);

-- 3. Tạo chỉ mục không gian (Spatial GIST Index) cho vi_tri và ranh_gioi
CREATE INDEX IF NOT EXISTS idx_vung_trong_vi_tri ON public.vung_trong USING GIST (vi_tri);
CREATE INDEX IF NOT EXISTS idx_vung_trong_ranh_gioi ON public.vung_trong USING GIST (ranh_gioi);

-- 4. Tạo chỉ mục tìm kiếm thuộc tính thông thường (B-Tree Index)
CREATE INDEX IF NOT EXISTS idx_vung_trong_msvt_moi ON public.vung_trong (msvt_moi);
CREATE INDEX IF NOT EXISTS idx_vung_trong_msvt_cu ON public.vung_trong (msvt_cu);

-- 5. Tạo trigger tự động kích hoạt cập nhật updated_at
DROP TRIGGER IF EXISTS trg_vung_trong_updated_at ON public.vung_trong;
CREATE TRIGGER trg_vung_trong_updated_at
BEFORE UPDATE ON public.vung_trong
FOR EACH ROW
EXECUTE FUNCTION public.update_updated_at_column();
