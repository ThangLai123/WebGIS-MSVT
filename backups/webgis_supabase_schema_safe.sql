-- ==============================================================================
-- 6. KHÓA NGOẠI (FOREIGN KEYS)
-- ==============================================================================
-- Ràng buộc quan hệ giữa các bảng ứng dụng

DO $$
BEGIN
    -- Khóa ngoại vung_trong.deleted_by -> admin_users.id
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_vung_trong_deleted_by'
    ) THEN
        ALTER TABLE public.vung_trong
            ADD CONSTRAINT fk_vung_trong_deleted_by
            FOREIGN KEY (deleted_by)
            REFERENCES public.admin_users(id)
            ON DELETE SET NULL;
    END IF;

    -- Khóa ngoại msvt_import_jobs.uploaded_by -> admin_users.id
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'msvt_import_jobs_uploaded_by_fkey'
    ) THEN
        ALTER TABLE public.msvt_import_jobs
            ADD CONSTRAINT msvt_import_jobs_uploaded_by_fkey
            FOREIGN KEY (uploaded_by)
            REFERENCES public.admin_users(id)
            ON DELETE SET NULL;
    END IF;
END $$;

-- ==============================================================================
-- 7. BẢO MẬT SUPABASE: BẬT RLS VÀ THU HỒI TOÀN BỘ QUYỀN TRUY CẬP TRỰC TIẾP
-- ==============================================================================
-- Nguyên tắc: Không cho phép client công khai (anon / authenticated) truy vấn
-- trực tiếp vào database qua PostgREST để bảo vệ dữ liệu cá nhân (SĐT, Email, v.v.).
-- Mọi truy cập đều phải qua Backend FastAPI (kết nối bằng role postgres / service_role).

-- 7.1. Bảng public.admin_users: Khóa chặt 100%
ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.admin_users FROM anon, authenticated;
GRANT ALL ON TABLE public.admin_users TO postgres, service_role;

-- 7.2. Bảng public.vung_trong: Khóa chặt 100% quyền SELECT, INSERT, UPDATE, DELETE
ALTER TABLE public.vung_trong ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.vung_trong FROM anon, authenticated;
GRANT ALL ON TABLE public.vung_trong TO postgres, service_role;

-- 7.3. Bảng public.msvt_import_jobs: Khóa chặt 100%
ALTER TABLE public.msvt_import_jobs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.msvt_import_jobs FROM anon, authenticated;
GRANT ALL ON TABLE public.msvt_import_jobs TO postgres, service_role;

-- 7.4. Phân quyền Identity Sequences cho role quản trị
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO postgres, service_role;

COMMIT;

