-- ==============================================================================
-- WebGIS MSVT - Supabase PostgreSQL & PostGIS Schema Migration
-- ==============================================================================
-- Nguồn dữ liệu: PostgreSQL 16 (Docker webgis_postgis) -> PostGIS 3.4 (schema: public)
-- Đích dữ liệu:  Supabase PostgreSQL (Database: postgres) -> PostGIS 3.3.7+ (schema: extensions)
-- 
-- Lưu ý quan trọng cho Supabase:
-- 1. PostGIS được cài đặt mặc định trong schema 'extensions'.
-- 2. Khai báo kiểu không gian chuyển đổi từ public.geometry -> extensions.geometry.
-- 3. Thiết lập search_path = public, extensions để các hàm GIS (ST_Covers, ST_IsValid, v.v.)
--    hoạt động trong suốt mà không cần tiền tố schema.
-- 4. Không chứa các lệnh DROP, TRUNCATE, DELETE hay các role local đặc thù (webgis_admin).
-- ==============================================================================

SET statement_timeout = 0;
SET lock_timeout = 0;
SET idle_in_transaction_session_timeout = 0;
SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SET check_function_bodies = false;
SET client_min_messages = warning;
SET row_security = off;

-- Cấu hình search_path: Ưu tiên public cho bảng ứng dụng và extensions cho PostGIS
SET search_path = public, extensions;

-- ==============================================================================
-- 1. EXTENSIONS
-- ==============================================================================
-- Supabase đã kích hoạt sẵn PostGIS trong schema 'extensions'.
-- Lệnh dưới đây đảm bảo tính idempotent, không tạo lại và không di chuyển extension có sẵn.
CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA extensions;

-- Ghi chú: Các extension 'fuzzystrmatch' và 'postgis_topology' từ database nguồn
-- không được bất kỳ bảng, trường dữ liệu, trigger hay truy vấn nghiệp vụ nào của
-- WebGIS MSVT sử dụng nên được lược bỏ nhằm giữ schema gọn gàng và tránh xung đột quyền.

-- ==============================================================================
-- 2. TRIGGER FUNCTIONS
-- ==============================================================================

-- Hàm tự động cập nhật thời gian sửa đổi cho bảng admin_users
CREATE OR REPLACE FUNCTION public.update_admin_users_timestamp()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- Hàm tự động cập nhật thời gian sửa đổi cho bảng vung_trong
CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- ==============================================================================
-- 3. BẢNG: public.admin_users
-- ==============================================================================
-- Quản lý tài khoản quản trị viên và người xem, phục vụ xác thực bảo mật và phân quyền

CREATE TABLE IF NOT EXISTS public.admin_users (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.admin_users_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ),
    username character varying(50) NOT NULL,
    password_hash text NOT NULL,
    role character varying(20) DEFAULT 'viewer'::character varying NOT NULL,
    is_active boolean DEFAULT true NOT NULL,
    failed_login_attempts integer DEFAULT 0 NOT NULL,
    locked_until timestamp with time zone,
    last_login_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT admin_users_pkey PRIMARY KEY (id),
    CONSTRAINT uq_admin_users_username UNIQUE (username),
    CONSTRAINT chk_admin_users_failed_attempts CHECK ((failed_login_attempts >= 0)),
    CONSTRAINT chk_admin_users_role CHECK (((role)::text = ANY ((ARRAY['admin'::character varying, 'viewer'::character varying])::text[])))
);

COMMENT ON TABLE public.admin_users IS 'Bảng lưu trữ thông tin tài khoản quản trị và phân quyền hệ thống WebGIS MSVT';
COMMENT ON COLUMN public.admin_users.id IS 'Khóa chính định danh người dùng';
COMMENT ON COLUMN public.admin_users.username IS 'Tên đăng nhập duy nhất (tối đa 50 ký tự)';
COMMENT ON COLUMN public.admin_users.password_hash IS 'Chuỗi băm mật khẩu bằng thuật toán Argon2id';
COMMENT ON COLUMN public.admin_users.role IS 'Vai trò phân quyền: admin (toàn quyền) hoặc viewer (chỉ xem)';
COMMENT ON COLUMN public.admin_users.is_active IS 'Trạng thái hoạt động của tài khoản (true: kích hoạt, false: khóa)';
COMMENT ON COLUMN public.admin_users.failed_login_attempts IS 'Số lần đăng nhập thất bại liên tiếp (dùng chống brute-force)';
COMMENT ON COLUMN public.admin_users.locked_until IS 'Thời điểm hết hạn khóa tài khoản khi vượt quá giới hạn thử sai';
COMMENT ON COLUMN public.admin_users.last_login_at IS 'Thời điểm đăng nhập thành công gần nhất';
COMMENT ON COLUMN public.admin_users.created_at IS 'Thời điểm khởi tạo bản ghi';
COMMENT ON COLUMN public.admin_users.updated_at IS 'Thời điểm cập nhật bản ghi gần nhất';

-- Chỉ mục cho admin_users
CREATE INDEX IF NOT EXISTS idx_admin_users_role ON public.admin_users USING btree (role);
CREATE INDEX IF NOT EXISTS idx_admin_users_username ON public.admin_users USING btree (username);

-- Trigger cập nhật thời gian
DROP TRIGGER IF EXISTS trg_update_admin_users_timestamp ON public.admin_users;
CREATE TRIGGER trg_update_admin_users_timestamp
    BEFORE UPDATE ON public.admin_users
    FOR EACH ROW
    EXECUTE FUNCTION public.update_admin_users_timestamp();

-- ==============================================================================
-- 4. BẢNG: public.vung_trong
-- ==============================================================================
-- Bảng lõi quản lý dữ liệu không gian và thuộc tính của các Mã số Vùng trồng (MSVT)

CREATE TABLE IF NOT EXISTS public.vung_trong (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.vung_trong_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ),
    msvt_moi text,
    msvt_cu text,
    to_chuc_ca_nhan text,
    nguoi_dai_dien text,
    so_dien_thoai text,
    email text,
    toa_do_goc text,
    dia_chi_msvt text,
    loai_cay_trong text,
    so_ho_tham_gia integer,
    dien_tich_ha numeric(14,4),
    san_luong_tan_ha numeric(14,4),
    quy_trinh text,
    thi_truong text,
    -- Tương thích Supabase: kiểu dữ liệu geometry thuộc schema extensions
    vi_tri extensions.geometry(Point, 4326),
    ranh_gioi extensions.geometry(MultiPolygon, 4326),
    created_at timestamp with time zone DEFAULT now(),
    updated_at timestamp with time zone DEFAULT now(),
    tong_san_luong_tan numeric(14,4),
    is_deleted boolean DEFAULT false NOT NULL,
    deleted_at timestamp with time zone,
    deleted_by bigint,
    CONSTRAINT vung_trong_pkey PRIMARY KEY (id),
    CONSTRAINT check_dien_tich_ha CHECK (((dien_tich_ha IS NULL) OR (dien_tich_ha >= (0)::numeric))),
    CONSTRAINT check_san_luong_tan_ha CHECK (((san_luong_tan_ha IS NULL) OR (san_luong_tan_ha >= (0)::numeric))),
    CONSTRAINT check_so_ho_tham_gia CHECK (((so_ho_tham_gia IS NULL) OR (so_ho_tham_gia >= 0))),
    CONSTRAINT check_tong_san_luong_tan CHECK (((tong_san_luong_tan IS NULL) OR (tong_san_luong_tan >= (0)::numeric)))
);

COMMENT ON TABLE public.vung_trong IS 'Bảng dữ liệu không gian và thuộc tính Mã số Vùng trồng (MSVT) tỉnh Nghệ An';
COMMENT ON COLUMN public.vung_trong.vi_tri IS 'Tọa độ đại diện vùng trồng kiểu Point WGS84 (EPSG:4326)';
COMMENT ON COLUMN public.vung_trong.ranh_gioi IS 'Ranh giới đa giác vùng trồng kiểu MultiPolygon WGS84 (EPSG:4326)';
COMMENT ON COLUMN public.vung_trong.is_deleted IS 'Cờ đánh dấu xóa mềm (true: đã xóa, false: đang hoạt động)';
COMMENT ON COLUMN public.vung_trong.deleted_at IS 'Thời điểm bản ghi bị xóa mềm';
COMMENT ON COLUMN public.vung_trong.deleted_by IS 'ID của tài khoản admin thực hiện thao tác xóa mềm';

-- Chỉ mục BTree & GiST Spatial cho vung_trong
CREATE INDEX IF NOT EXISTS idx_vung_trong_is_deleted ON public.vung_trong USING btree (is_deleted);
CREATE INDEX IF NOT EXISTS idx_vung_trong_msvt_cu ON public.vung_trong USING btree (msvt_cu);
CREATE INDEX IF NOT EXISTS idx_vung_trong_msvt_moi ON public.vung_trong USING btree (msvt_moi);
CREATE INDEX IF NOT EXISTS idx_vung_trong_ranh_gioi ON public.vung_trong USING gist (ranh_gioi);
CREATE INDEX IF NOT EXISTS idx_vung_trong_vi_tri ON public.vung_trong USING gist (vi_tri);

-- Trigger cập nhật thời gian
DROP TRIGGER IF EXISTS trg_vung_trong_updated_at ON public.vung_trong;
CREATE TRIGGER trg_vung_trong_updated_at
    BEFORE UPDATE ON public.vung_trong
    FOR EACH ROW
    EXECUTE FUNCTION public.update_updated_at_column();

