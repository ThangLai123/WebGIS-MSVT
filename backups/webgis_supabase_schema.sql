COMMENT ON TABLE public.msvt_import_jobs IS 'Bảng lưu vết các phiên nhập dữ liệu MSVT từ file Excel';
COMMENT ON COLUMN public.msvt_import_jobs.status IS 'Trạng thái phiên nhập: uploaded, validated, committed, cancelled, failed';

-- Chỉ mục cho msvt_import_jobs
CREATE INDEX IF NOT EXISTS idx_msvt_import_jobs_created_at ON public.msvt_import_jobs USING btree (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_msvt_import_jobs_status ON public.msvt_import_jobs USING btree (status);
CREATE INDEX IF NOT EXISTS idx_msvt_import_jobs_uploaded_by ON public.msvt_import_jobs USING btree (uploaded_by);

-- ==============================================================================
-- 6. KHÓA NGOẠI (FOREIGN KEYS)
-- ==============================================================================
-- Khởi tạo sau khi các bảng cha (admin_users) đã hoàn tất tạo dựng

DO $$
BEGIN
    -- Khóa ngoại vung_trong.deleted_by -> admin_users.id
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_vung_trong_deleted_by'
    ) THEN
        ALTER TABLE public.vung_trong
            ADD CONSTRAINT fk_vung_trong_deleted_by
            FOREIGN KEY (deleted_by)
            REFERENCES public.admin_users(id)
            ON DELETE SET NULL;
    END IF;

    -- Khóa ngoại msvt_import_jobs.uploaded_by -> admin_users.id
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'msvt_import_jobs_uploaded_by_fkey'
    ) THEN
        ALTER TABLE public.msvt_import_jobs
            ADD CONSTRAINT msvt_import_jobs_uploaded_by_fkey
            FOREIGN KEY (uploaded_by)
            REFERENCES public.admin_users(id)
            ON DELETE SET NULL;
    END IF;
END $$;

