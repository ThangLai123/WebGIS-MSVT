-- 5. BẢNG: public.msvt_import_jobs
-- ==============================================================================
-- Quản lý các phiên import Excel, kiểm định dữ liệu và lưu vết lịch sử import MSVT

CREATE TABLE IF NOT EXISTS public.msvt_import_jobs (
    id character varying(50) NOT NULL,
    filename character varying(255) NOT NULL,
    file_hash character varying(64) NOT NULL,
    uploaded_by bigint,
    sheet_name character varying(100),
    header_row integer DEFAULT 1,
    data_start_row integer DEFAULT 2,
    mapping_config jsonb,
    total_rows integer DEFAULT 0 NOT NULL,
    valid_count integer DEFAULT 0 NOT NULL,
    warning_count integer DEFAULT 0 NOT NULL,
    duplicate_count integer DEFAULT 0 NOT NULL,
    error_count integer DEFAULT 0 NOT NULL,
